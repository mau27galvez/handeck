import { mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { PutObjectCommand, S3Client } from "@aws-sdk/client-s3";
import { env } from "@handeck/env/server";
import { BASIC_MODEL, Deck, Note, Package } from "@handeck/genanki-ts";

type NoteData = {
  id: string;
  simplifiedHanzi: string;
  diacriticPinyin: string;
  meaning: string;
};

type DeckPackageInput = {
  deckId: string;
  userId: string;
  templateName: string;
  notes: NoteData[];
};

function createS3Client() {
  return new S3Client({
    region: env.S3_REGION,
    ...(env.S3_ENDPOINT
      ? {
          endpoint: env.S3_ENDPOINT,
          forcePathStyle: env.S3_FORCE_PATH_STYLE,
        }
      : {}),
  });
}

export async function writeDeckPackageToS3({
  deckId,
  userId,
  templateName,
  notes,
}: DeckPackageInput) {
  const deck = new Deck({
    id: deckNumberFromUuid(deckId),
    name: templateName,
    description: "Generated by Handeck.",
  });

  for (const note of notes) {
    deck.addNote(
      new Note({
        model: BASIC_MODEL,
        fields: [
          note.simplifiedHanzi,
          [note.diacriticPinyin, note.meaning].filter(Boolean).join("\n\n"),
        ],
        tags: ["handeck"],
        guid: `handeck:${note.id}`,
      }),
    );
  }

  const objectKey = `decks/${userId}/${deckId}.apkg`;
  const tempDir = await mkdtemp(join(tmpdir(), "handeck-deck-package-"));
  const apkgPath = join(tempDir, "deck.apkg");

  try {
    await new Package(deck).writeToFile(apkgPath);
    const body = await readFile(apkgPath);

    const s3Client = createS3Client();
    await s3Client.send(
      new PutObjectCommand({
        Bucket: env.S3_BUCKET,
        Key: objectKey,
        Body: body,
        ContentType: "application/octet-stream",
      }),
    );

    return { objectKey };
  } finally {
    await rm(tempDir, { recursive: true, force: true });
  }
}

function deckNumberFromUuid(id: string) {
  const numericId = Number.parseInt(id.replaceAll("-", "").slice(0, 8), 16);
  return numericId % 2_147_483_647 || 1;
}
