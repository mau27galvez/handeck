import { readFileSync } from "node:fs";
import { mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Deck, Model, Note, Package } from "@handeck/genanki-ts";

import { getDeckObjectKey, uploadDeckPackage } from "./deckStorage";

const templatesDir = join(dirname(fileURLToPath(import.meta.url)), "anki", "templates");
const frontTemplate = readFileSync(join(templatesDir, "front.html"), "utf8");
const backTemplate = readFileSync(join(templatesDir, "back.html"), "utf8");
const cardStyles = readFileSync(join(templatesDir, "style.css"), "utf8");

const HANDECK_VOCAB_MODEL = new Model({
  id: 1760000000,
  name: "Handeck Vocabulary (genanki)",
  fields: [
    { name: "Word Hanzi", font: "Noto Sans SC" },
    { name: "Word Pinyin", font: "Noto Sans SC" },
    { name: "Word Translations", font: "Noto Sans SC" },
    { name: "Sentence Hanzi", font: "Noto Sans SC" },
    { name: "Sentence Pinyin", font: "Noto Sans SC" },
    { name: "Sentence Translation", font: "Noto Sans SC" },
  ],
  templates: [
    {
      name: "Card 1",
      qfmt: frontTemplate,
      afmt: backTemplate,
    },
  ],
  css: cardStyles,
});

type NoteData = {
  id: string;
  simplifiedHanzi: string;
  diacriticPinyin: string;
  meaning: string;
  sentence: string;
  sentencePinyin: string;
  sentenceTranslation: string;
};

type DeckPackageInput = {
  deckId: string;
  userId: string;
  templateName: string;
  notes: NoteData[];
};

export async function writeDeckPackageToS3({
  deckId,
  userId,
  templateName,
  notes,
}: DeckPackageInput) {
  const objectKey = getDeckObjectKey(userId, deckId);
  const tempDir = await mkdtemp(join(tmpdir(), "handeck-deck-package-"));
  const apkgPath = join(tempDir, "deck.apkg");

  try {
    const deck = new Deck({
      id: deckNumberFromUuid(deckId),
      name: templateName,
      description: "Generated by Handeck.",
    });

    for (const note of notes) {
      deck.addNote(
        new Note({
          model: HANDECK_VOCAB_MODEL,
          fields: [
            note.simplifiedHanzi,
            note.diacriticPinyin,
            note.meaning,
            note.sentence,
            note.sentencePinyin,
            note.sentenceTranslation,
          ],
          tags: ["handeck"],
          // we may want to review this in the future
          guid: `handeck:${note.id}`,
        }),
      );
    }

    await new Package(deck).writeToFile(apkgPath);
    const body = await readFile(apkgPath);
    await uploadDeckPackage(objectKey, body);

    return { objectKey };
  } finally {
    await rm(tempDir, { recursive: true, force: true });
  }
}

function deckNumberFromUuid(id: string) {
  const numericId = Number.parseInt(id.replaceAll("-", "").slice(0, 8), 16);
  return numericId % 2_147_483_647 || 1;
}
