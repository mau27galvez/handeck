import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

type DeckPackageWord = {
  id: string;
  simplifiedHanzi: string;
  diacriticPinyin: string;
  meaning: string;
};

type DeckPackageInput = {
  deckId: string;
  templateName: string;
  words: DeckPackageWord[];
};

export async function writeDeckPackageToVoid({ deckId, templateName, words }: DeckPackageInput) {
  if (typeof Bun === "undefined") return;

  const { BASIC_MODEL, Deck, Note, Package } = await import("@handeck/genanki-ts");

  const deck = new Deck({
    id: deckNumberFromUuid(deckId),
    name: templateName,
    description: "Generated by Handeck.",
  });

  for (const word of words) {
    deck.addNote(
      new Note({
        model: BASIC_MODEL,
        fields: [
          word.simplifiedHanzi,
          [word.diacriticPinyin, word.meaning].filter(Boolean).join("\n\n"),
        ],
        tags: ["handeck"],
        guid: `handeck:${word.id}`,
      }),
    );
  }

  const tempDir = await mkdtemp(join(tmpdir(), "handeck-deck-package-"));
  try {
    await new Package(deck).writeToFile(join(tempDir, "deck.apkg"));
  } finally {
    await rm(tempDir, { recursive: true, force: true });
  }
}

function deckNumberFromUuid(id: string) {
  const numericId = Number.parseInt(id.replaceAll("-", "").slice(0, 8), 16);
  return numericId % 2_147_483_647 || 1;
}
