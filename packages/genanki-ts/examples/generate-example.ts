import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { BASIC_MODEL, Deck, Note, Package } from "../src/index";

const packageRoot = dirname(fileURLToPath(import.meta.url));
const outputPath = resolve(packageRoot, process.argv[2] ?? "example.apkg");

const deck = new Deck({
  id: 2059400110,
  name: "Handeck Example Deck",
  description: "Generated by @handeck/genanki-ts/examples/generate-example.ts",
});

deck.addNote(
  new Note({
    model: BASIC_MODEL,
    fields: ["Capital of Argentina", "Buenos Aires"],
    tags: ["example", "geography"],
  }),
);

deck.addNote(
  new Note({
    model: BASIC_MODEL,
    fields: ["Capital of Taiwan", "Taipei"],
    tags: ["example", "geography"],
  }),
);

deck.addNote(
  new Note({
    model: BASIC_MODEL,
    fields: ["What is 2 + 2?", "4"],
    tags: ["example", "math"],
  }),
);

await new Package(deck).writeToFile(outputPath);

console.log(`Wrote ${outputPath}`);
console.log("Import it in Anki with File → Import…");
